//! 用户级状态写入 shim（D27 自包含 + D28 用户级常驻）：hook 与 hst 二进制
//! 解耦，注册与 shim 常驻 `~/.hst/hooks/`（用户裁 2026-09-11「hook 应用户
//! 全局」，对齐 codex 用户层形态），各家 hook 注册指向 shim——state 通道
//! 零 hst 依赖，hst 可任意时刻无痛升级轮换，未 init 的项目也有状态数据。
//! 状态落 `~/.hst/state/` 按 session 分键（D28，防 herdr 多会话互踩）：
//! 默认双写 `<agent>.json`（agent 最新，供无 session 标识的消费面）加
//! `<agent>-<session>.json`（session 键，状态栏按当前会话直读）；
//! SessionEnd 删本 session 键文件（GC，崩溃残留由 hst hook 侧陈旧清扫）。
//! `HST_STATE_FILE` 覆盖优先且互斥（单文件语义，verify 与测试用）。
//! secretguard 由 shim fail-open 委托加 M060a 白名单：PreToolUse /
//! UserPromptSubmit 时 hst 在位则转发 payload，仅「exit 2 且 stderr 带
//! `hst secretguard:` 前缀」判定为自判 block 透传 2 并回放原因；hst 故障的其余非零（升级期坏二进制、CLI 契约漂移含 clap 用法错的 exit 2）一律
//! fail-open 放行，不在位同放行（state 已写）——护无痛轮换。
//! `hst hook` 保留为手动入口与委托目标（含完整 notification 形状解析）。
//! cmd 形态两级（用户裁 2026-09-10：jq 归 ome 部署，shim 部署前探 PATH）：
//! jq 在位用 jq 解析（转义免疫、ts 取 jq now），缺位回落 findstr 硬解析并
//! warn 指向 `ark install jq`（ome 更名 Ark 随批）。sh 侧 sed 是 POSIX 基线不引依赖。
//! session 标识三源：payload `session_id`（claude/codex）、`sessionId`
//! （kimi）、grok runner 注入的 `GROK_SESSION_ID` env（payload 无该字段）。

/// Windows cmd shim，jq 形态（首选）。约定：`%1` = agent 名；stdin = hook
/// payload JSON；状态根 = `%USERPROFILE%\.hst\state`（用户级常驻，D28）；
/// `HST_STATE_FILE` 覆盖优先（互斥单写）。字段提取与 state JSON
/// 生成都走 jq：`--arg` 传值让 jq 程序体内零双引号，绕开 cmd 引号地狱；
/// ts 用 `now|floor` 取纪元秒（locale 无关）。guard 委托前 payload 留在
/// 临时文件。
pub const STATE_CMD_JQ: &str = r#"@echo off
rem generated by hst init; rerun hst init to sync (D28 user-level state shim, jq form)
setlocal EnableDelayedExpansion
set "AGENT=%~1"
if "%AGENT%"=="" exit /b 0
set "TMPF=%TEMP%\hst-state-%RANDOM%%RANDOM%.json"
more > "%TMPF%" 2>nul
set "ERAW="
for /f "usebackq delims=" %%a in (`jq -r ".hook_event_name // .hookEventName // empty" "%TMPF%" 2^>nul`) do (
  if not defined ERAW set "ERAW=%%a"
)
set "SID="
for /f "usebackq delims=" %%b in (`jq -r ".session_id // .sessionId // empty" "%TMPF%" 2^>nul`) do (
  if not defined SID set "SID=%%b"
)
if not defined SID if defined GROK_SESSION_ID set "SID=%GROK_SESSION_ID%"
set "STATE=unknown"
if /i "!ERAW!"=="SessionStart" set "STATE=idle"
if /i "!ERAW!"=="Stop" set "STATE=idle"
if /i "!ERAW!"=="SessionEnd" set "STATE=idle"
if /i "!ERAW!"=="Interrupt" set "STATE=idle"
if /i "!ERAW!"=="UserPromptSubmit" set "STATE=working"
if /i "!ERAW!"=="PreToolUse" set "STATE=working"
if /i "!ERAW!"=="PostToolUse" set "STATE=working"
if /i "!ERAW!"=="PostToolUseFailure" set "STATE=working"
if /i "!ERAW!"=="SubagentStart" set "STATE=working"
if /i "!ERAW!"=="SubagentStop" set "STATE=working"
if /i "!ERAW!"=="PreCompact" set "STATE=working"
if /i "!ERAW!"=="PermissionResult" set "STATE=working"
if /i "!ERAW!"=="PermissionRequest" set "STATE=blocked"
if /i "!ERAW!"=="Notification" (
  set "STATE=unknown"
  jq -e --arg k permission "(.notification_type // .notificationType // .matcher // .message // empty) | tostring | contains($k)" "%TMPF%" >nul 2>nul && set "STATE=blocked"
)
set "STATE_DIR=%USERPROFILE%\.hst\state"
set "TARGET="
if defined HST_STATE_FILE set "TARGET=%HST_STATE_FILE%"
if not defined TARGET set "TARGET=%STATE_DIR%\%AGENT%.json"
for %%d in ("!TARGET!") do if not exist "%%~fd\.." mkdir "%%~fd\.." 2>nul
jq -n --arg state "!STATE!" --arg event "!ERAW!" --arg agent "%AGENT%" --arg session "!SID!" "{state:$state,event:$event,agent:$agent,session:$session,ts:(now|floor)}" > "!TARGET!"
if not defined HST_STATE_FILE (
  if defined SID (
    copy /y "!TARGET!" "!STATE_DIR!\%AGENT%-!SID!.json" >nul 2>nul
    if /i "!ERAW!"=="SessionEnd" del "!STATE_DIR!\%AGENT%-!SID!.json" >nul 2>nul
  )
)
if /i "!ERAW!"=="PreToolUse" goto guard
if /i "!ERAW!"=="UserPromptSubmit" goto guard
del "%TMPF%" >nul 2>nul
exit /b 0
:guard
where hst >nul 2>nul
if errorlevel 1 (
  del "%TMPF%" >nul 2>nul
  exit /b 0
)
set "ERRF=%TEMP%\hst-guard-%RANDOM%%RANDOM%.err"
type "%TMPF%" | hst hook status --agent %AGENT% 2>"%ERRF%"
set "RC=%errorlevel%"
rem M060a guard 透传白名单：仅「hst 自判 block」（exit 2 且 stderr 带
rem hst secretguard: 前缀）才透传 2 并回放原因；hst 故障的非零（升级期
rem 坏二进制、CLI 契约漂移含 clap 用法错也是 exit 2）一律 fail-open
rem 放行，护无痛轮换。
if not "%RC%"=="2" goto guardpass
findstr /b /c:"hst secretguard:" "%ERRF%" >nul 2>nul
if errorlevel 1 goto guardpass
type "%ERRF%" >&2
del "%TMPF%" >nul 2>nul
del "%ERRF%" >nul 2>nul
exit /b 2
:guardpass
del "%TMPF%" >nul 2>nul
del "%ERRF%" >nul 2>nul
exit /b 0
"#;

