/// POSIX sh shim（Linux = bash、mac = zsh 同一语义；shebang 由部署侧按宿主
/// 写 bash 或 zsh）。`$1` = agent；stdin = payload；状态根 =
/// `$HOME/.hst/state`（用户级常驻，D28；HOME 缺位的退化环境直接退出，
/// fail-open）；ts 取纪元秒。sed 是 POSIX 基线（jq 不作 Unix 前置依赖）。
pub const STATE_SH: &str = r#"#!/usr/bin/env bash
# generated by hst init; rerun hst init to sync (D28 user-level state shim)
agent="${1:-}"
[ -n "$agent" ] || exit 0
payload="$(cat)"
raw="$(printf '%s' "$payload" | sed -n 's/.*"hook[_]event[_]name"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p;t')"
[ -n "$raw" ] || raw="$(printf '%s' "$payload" | sed -n 's/.*"hookEventName"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p;t')"
event="$(printf '%s' "$raw" | tr '[:upper:]' '[:lower:]' | tr -cd '[:alnum:]')"
sid="$(printf '%s' "$payload" | sed -n 's/.*"session[_]id"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p;t')"
[ -n "$sid" ] || sid="$(printf '%s' "$payload" | sed -n 's/.*"sessionId"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p;t')"
if [ -z "$sid" ] && [ -n "$GROK_SESSION_ID" ]; then sid="$GROK_SESSION_ID"; fi
case "$event" in
  sessionstart|stop|sessionend|interrupt|idle) state=idle ;;
  userpromptsubmit|userpromptuse|pretooluse|posttooluse|posttoolusefailure|subagentstart|subagentstop|precompact|permissionresult|working) state=working ;;
  permissionrequest|blocked|elicitation|elicitationresult) state=blocked ;;
  notification)
    state=unknown
    case "$payload" in *permission*) state=blocked ;; esac
    ;;
  *) state=unknown ;;
esac
if [ -n "$HST_STATE_FILE" ]; then
  target="$HST_STATE_FILE"
else
  [ -n "$HOME" ] || exit 0
  state_dir="$HOME/.hst/state"
  mkdir -p "$state_dir"
  target="$state_dir/$agent.json"
fi
ts="$(date +%s)"
printf '{"state":"%s","event":"%s","agent":"%s","session":"%s","ts":%s}\n' \
  "$state" "$event" "$agent" "$sid" "$ts" > "$target"
if [ -z "$HST_STATE_FILE" ] && [ -n "$sid" ]; then
  keyed="$state_dir/$agent-$sid.json"
  cp -f "$target" "$keyed"
  if [ "$event" = "sessionend" ]; then rm -f "$keyed"; fi
fi
case "$event" in
  pretooluse|userpromptsubmit)
    if command -v hst >/dev/null 2>&1; then
      # M060a guard 透传白名单：仅「hst 自判 block」（exit 2 且 stderr 带
      # hst secretguard: 前缀）才透传 2 并回放原因；hst 故障的非零一律
      # fail-open 放行，护无痛轮换。
      errf="$(mktemp "${TMPDIR:-/tmp}/hst-guard.XXXXXX" 2>/dev/null || printf '%s/hst-guard.%s' "${TMPDIR:-/tmp}" "$$")"
      printf '%s' "$payload" | hst hook status --agent "$agent" 2>"$errf"
      rc=$?
      if [ "$rc" -eq 2 ] && grep -q "^hst secretguard:" "$errf"; then
        cat "$errf" >&2
        rm -f "$errf"
        exit 2
      fi
      rm -f "$errf"
    fi
    ;;
esac
exit 0
"#;

/// 部署时替换 shebang 行得到 zsh 变体（语义同 bash 形；zsh 无 bashisms 可用
/// 之处已避开，dirname/date/sed/case 全兼容）。
pub fn state_sh_for(shell: &str) -> String {
    let body = STATE_SH.trim_start_matches("#!/usr/bin/env bash\n");
    format!("#!/usr/bin/env {shell}\n{body}")
}

/// Windows PowerShell shim（D39，2026-09-13 宿主实弹）：claude 在 Windows
/// 的 hook 执行 shell 是 POSIX sh 系（Git Bash 或 WSL 互操作形），直路径
/// `.cmd` 在 WSL 形不认盘符、`cmd.exe /c` 在 Git Bash 被 MSYS 参数转换吃
/// 掉 `/c`——注册串改 `powershell.exe -NoProfile -ExecutionPolicy Bypass -File
/// <本文件> <agent>`（按名解析 powershell.exe 恒在、无前导斜杠参数不触发
/// MSYS 转换、Windows 路径只在参数位，sh 系与 PS 与 cmd 三态成立，与
/// 状态栏的 pwsh -File 同构）。`$args[0]` = agent；stdin = payload；事件
/// 映射与 STATE_SH 同集（大小写不敏感）；state 落盘**无 BOM**（verify 侧
/// serde_json 直接解析，PS5.1 的 utf8 编码带 BOM 会炸）；guard 委托与
/// M060a 白名单同款（payload 字节保真走临时文件，不走 PS 管道编码）。
pub const STATE_PS1: &str = r#"# generated by hst init; rerun hst init to sync (D39 sh-compatible state shim, ps1 form)
$ErrorActionPreference = 'SilentlyContinue'
$agent = "$($args[0])"
if (-not $agent) { exit 0 }
# $input 读法（codex review G1 订正 F3）：PS 5.1 宿主启动时把重定向 stdin
# 预读进管道输入集合，[Console]::OpenStandardInput 的新 StreamReader 从流
# 末尾起读恒空；$input 是宿主已收集的行集，join 还原 payload（Out-String
# 会补尾换行，对 JSON 解析与 guard 临时文件均无碍）。读前先把
# InputEncoding 钉 UTF-8（$input 惰性枚举，先设后读）。保真口径（H1 对齐
# 实测）：ASCII 载荷保真（event / state / session 实跑字段全对）；非
# ASCII 解码随宿主控制台代码页，cmd 重定向与 Git Bash 管道实测中文完好、
# WSL interop 与 CP936 控制台两腿实测仍乱码，非 ASCII 保真不作为本 shim
# 的已验证结论（session_id 实践为 ASCII UUID）。
try { [Console]::InputEncoding = New-Object Text.UTF8Encoding $false } catch { }
$raw = if ($input) { ($input -join "`n") } else { '' }
$event = ''
$sid = ''
$j = $null
try { $j = $raw | ConvertFrom-Json } catch { }
if ($null -ne $j) {
  $event = [string]$j.hook_event_name
  if (-not $event) { $event = [string]$j.hookEventName }
  $sid = [string]$j.session_id
  if (-not $sid) { $sid = [string]$j.sessionId }
}
if (-not $sid -and $env:GROK_SESSION_ID) { $sid = $env:GROK_SESSION_ID }
# 事件映射与 STATE_SH 同集（codex review F4）：Elicitation 系、字面直通
# token、Notification 全 payload 扫 permission。
$state = 'unknown'
switch ($event) {
  'SessionStart' { $state = 'idle' }
  'Stop' { $state = 'idle' }
  'SessionEnd' { $state = 'idle' }
  'Interrupt' { $state = 'idle' }
  'idle' { $state = 'idle' }
  'UserPromptSubmit' { $state = 'working' }
  'PreToolUse' { $state = 'working' }
  'PostToolUse' { $state = 'working' }
  'PostToolUseFailure' { $state = 'working' }
  'SubagentStart' { $state = 'working' }
  'SubagentStop' { $state = 'working' }
  'PreCompact' { $state = 'working' }
  'PermissionResult' { $state = 'working' }
  'working' { $state = 'working' }
  'PermissionRequest' { $state = 'blocked' }
  'Elicitation' { $state = 'blocked' }
  'ElicitationResult' { $state = 'blocked' }
  'blocked' { $state = 'blocked' }
  'Notification' { $state = 'unknown' }
  default { $state = 'unknown' }
}
if ($event -eq 'Notification' -and $raw -match 'permission') { $state = 'blocked' }
$override = "$env:HST_STATE_FILE"
$stateDir = Join-Path $env:USERPROFILE '.hst\state'
if ($override) {
  $target = $override
} else {
  if (-not (Test-Path $stateDir)) { New-Item -ItemType Directory -Force $stateDir | Out-Null }
  $target = Join-Path $stateDir "$agent.json"
}
$d = Split-Path -Parent $target
if (-not (Test-Path $d)) { New-Item -ItemType Directory -Force $d | Out-Null }
$ts = [DateTimeOffset]::UtcNow.ToUnixTimeSeconds()
$body = '{"state":"' + $state + '","event":"' + $event + '","agent":"' + $agent + '","session":"' + $sid + '","ts":' + $ts + '}'
[IO.File]::WriteAllText($target, $body, (New-Object Text.UTF8Encoding $false))
if (-not $override -and $sid) {
  $keyed = Join-Path $stateDir "$agent-$sid.json"
  [IO.File]::WriteAllText($keyed, $body, (New-Object Text.UTF8Encoding $false))
  if ($event -eq 'SessionEnd') { Remove-Item $keyed -Force -ErrorAction SilentlyContinue }
}
if ($event -eq 'PreToolUse' -or $event -eq 'UserPromptSubmit') {
  $tmp = [IO.Path]::GetTempPath()
  $tmpf = Join-Path $tmp ('hst-state-' + [Guid]::NewGuid().ToString('N') + '.json')
  $errf = Join-Path $tmp ('hst-guard-' + [Guid]::NewGuid().ToString('N') + '.err')
  [IO.File]::WriteAllText($tmpf, $raw, (New-Object Text.UTF8Encoding $false))
  $rc = -1
  try {
    $p = Start-Process -FilePath 'hst' -ArgumentList @('hook', 'status', '--agent', $agent) -RedirectStandardInput $tmpf -RedirectStandardError $errf -NoNewWindow -PassThru -Wait
    $rc = $p.ExitCode
  } catch { }
  if ($rc -eq 2 -and (Test-Path $errf)) {
    $err = [IO.File]::ReadAllText($errf)
    if ($err.StartsWith('hst secretguard:')) {
      [Console]::Error.Write($err)
      Remove-Item $tmpf, $errf -Force -ErrorAction SilentlyContinue
      exit 2
    }
  }
  Remove-Item $tmpf, $errf -Force -ErrorAction SilentlyContinue
}
exit 0
"#;

