/// CRLF 规整（cmd 批处理对 LF-only 的 goto/label 扫描有历史坑；统一落 CRLF）。
fn crlf(s: &str) -> String {
    s.replace("\r\n", "\n").replace('\n', "\r\n")
}

/// 的写前比对面（细则见 R002 与模块文档）。
fn write_if_changed(path: &std::path::Path, content: &str) -> Result<bool, String> {
    if std::fs::read_to_string(path)
        .map(|old| old == content)
        .unwrap_or(false)
    {
        return Ok(false);
    }
    std::fs::write(path, content).map_err(|e| format!("{}: {e}", path.display()))?;
    Ok(true)
}

/// 宿主 shell 选择（M060b 抽出成映射）：macOS 落 zsh shebang（缺
/// /usr/bin/bash 的兜底；两 shebang 皆兼容），其余 bash。
pub fn host_shell() -> &'static str {
    if cfg!(target_os = "macos") {
        "zsh"
    } else {
        "bash"
    }
}

/// # Errors
///
/// 失败返回 `String` 错误（路径与原因；网络与解析类见模块文档）。
/// 部署 shim 文件集到 hst 自管根的 `hooks/`（D28 用户级常驻：
/// `<hst_home>/hooks/`，调用方传 `install::hst_home()`；测试传临时根）。
/// 三份脚本全侧落齐（跨 OS 共享并存：Windows init 也备好 .sh、Unix init
/// 也备好 .cmd；+x 只在 Unix 生效）。cmd 主 shim按 jq 探测选形态（D27
/// 的用户裁定面（细则见 R002 与模块文档）。
/// 返回 (实写路径, 警告)。
pub fn deploy_shims(
    root_param: &std::path::Path,
) -> Result<(Vec<std::path::PathBuf>, Vec<String>), String> {
    deploy_shims_with(root_param, host_shell())
}

/// # Errors
///
/// 失败返回 `String` 错误（路径与原因；网络与解析类见模块文档）。
/// Test seam（M060b）：shell 选择注入（zsh 变体在 Windows/WSL 编译期
/// cfg! 分支测不到的根因消除；prod 经 deploy_shims 走 host_shell）。
pub fn deploy_shims_with(
    root_param: &std::path::Path,
    shell: &str,
) -> Result<(Vec<std::path::PathBuf>, Vec<String>), String> {
    use std::path::PathBuf;
    let dir = root_param.join("hooks");
    std::fs::create_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    let mut wrote: Vec<PathBuf> = Vec::new();
    let mut warns = Vec::new();
    let cmd_body = if crate::pathutil::find_on_path("jq").is_some() {
        STATE_CMD_JQ.to_string()
    } else {
        warns.push(
            "jq not on PATH: state shim deployed findstr fallback; \
             ark install jq then rerun hst init to upgrade"
                .to_string(),
        );
        STATE_CMD.to_string()
    };
    let cmd = dir.join("hst-state.cmd");
    if write_if_changed(&cmd, &crlf(&cmd_body))? {
        wrote.push(cmd);
    }
    // D39：ps1 形 shim（Windows 注册的 sh 兼容载体），全侧落齐与 cmd/sh
    // 并存（跨 OS 共享项目同 D28 语义）。**带 UTF-8 BOM 落盘**：Windows
    // PowerShell 5.1 对无 BOM 的 .ps1 按系统 ANSI 码页解析，脚本内的中文
    // 注释会乱码破坏语句（codex review G1 追因：$input 读法本身三态全通，
    // 是被注释乱码殃及；纯 ASCII 探针正常、真 shim 空解析的现场复现）。
    // state 输出文件仍是无 BOM（verify 侧 serde_json 不吃 BOM）。
    let ps1 = dir.join("hst-state.ps1");
    if write_if_changed(&ps1, &format!("\u{feff}{}", STATE_PS1))? {
        wrote.push(ps1);
    }
    let grok = dir.join("hst-state-grok.cmd");
    if write_if_changed(&grok, &crlf(STATE_GROK_CMD))? {
        wrote.push(grok);
    }
    let sh = dir.join("hst-state.sh");
    let sh_body = state_sh_for(shell);
    if write_if_changed(&sh, &sh_body)? {
        wrote.push(sh.clone());
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(&sh, std::fs::Permissions::from_mode(0o755));
    }
    // D45 oma 遗产清扫：pristine 合并搬进用户根的旧名 shim（oma-state.*）
    // 幂等删除——P0047 观察面二收口（新名四件全落齐后旧名件再无消费面）。
    for legacy in [
        "oma-state.cmd",
        "oma-state-grok.cmd",
        "oma-state.sh",
        "oma-state.ps1",
    ] {
        let p = dir.join(legacy);
        if p.exists() {
            match std::fs::remove_file(&p) {
                Ok(()) => warns.push(format!(
                    "retired legacy shim {} (oma-era name, D45 sweep)",
                    p.display()
                )),
                Err(e) => warns.push(format!("could not retire legacy shim {}: {e}", p.display())),
            }
        }
    }
    Ok((wrote, warns))
}

